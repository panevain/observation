#!/usr/bin/env bash
# Sets up the production host for Deploy (docs/deploy.md). Run as root from a checkout of this
# repository on the host, with the public half of the deploy key:
#
#   sudo scripts/deploy-host-setup.sh "ssh-ed25519 AAAA... observation-deploy"
#
# Needs Docker with the Compose plugin, git, curl and flock. It
#   * installs cosign at the version and checksum in mise.ci.lock, as /usr/local/bin/cosign;
#   * creates the observation-deploy user (home /var/lib/observation-deploy, in the docker group);
#   * installs scripts/deploy-host.sh as /usr/local/libexec/observation-deploy and makes it the
#     only thing the deploy key can run (authorized_keys `restrict,command=...`, owned by root);
#   * writes /etc/observation/observation.env, with a fresh OBS_REGIONS_TOKEN, unless it exists.
# Run it again after a `git pull` to update the script or cosign, or to replace the key.
set -euo pipefail

key="${1:?usage: $0 'ssh-ed25519 AAAA... comment'}"
[ "$(id -u)" -eq 0 ] || { echo "run as root (sudo)" >&2; exit 1; }
cd "$(dirname "$0")/.."

user=observation-deploy
home=/var/lib/observation-deploy
cmd=/usr/local/libexec/observation-deploy
env_file=/etc/observation/observation.env

for tool in docker git curl flock sha256sum openssl getent; do
  command -v "${tool}" >/dev/null 2>&1 || { echo "${tool} is not installed" >&2; exit 1; }
done
docker compose version >/dev/null 2>&1 || { echo "the Docker Compose plugin is not installed" >&2; exit 1; }
# One ed25519 key and nothing else: no options of its own, no second line.
[[ "${key}" =~ ^ssh-ed25519\ [A-Za-z0-9+/]+=*(\ [A-Za-z0-9@._-]+)?$ ]] ||
  { echo "not one ssh-ed25519 public key: ${key}" >&2; exit 1; }

# cosign, as CI pins it.
case "$(uname -m)" in
  x86_64 | amd64) platform=linux-x64 ;;
  aarch64 | arm64) platform=linux-arm64 ;;
  *) echo "no cosign build in mise.ci.lock for $(uname -m)" >&2; exit 1 ;;
esac
read -r url sum < <(awk -v s="[tools.cosign.\"platforms.${platform}\"]" '
  $0 == s { f = 1; next }
  f && /^\[/ { exit }
  f && $1 == "url" { gsub(/"/, "", $3); u = $3 }
  f && $1 == "checksum" { gsub(/"|sha256:/, "", $3); c = $3 }
  END { print u, c }' mise.ci.lock)
[[ "${url}" == https://github.com/sigstore/cosign/releases/download/* && "${sum}" =~ ^[0-9a-f]{64}$ ]] ||
  { echo "could not read cosign's ${platform} download from mise.ci.lock" >&2; exit 1; }
if ! echo "${sum}  /usr/local/bin/cosign" | sha256sum --check --status 2>/dev/null; then
  tmp="$(mktemp)"
  trap 'rm -f "${tmp}"' EXIT
  curl -fsSL --proto '=https' -o "${tmp}" "${url}"
  echo "${sum}  ${tmp}" | sha256sum --check --quiet
  install -m 0755 -o root -g root "${tmp}" /usr/local/bin/cosign
  echo "installed cosign from ${url}"
fi

# The deploy user. `*`, not a locked `!`: no password, but sshd still accepts its key.
if ! id "${user}" >/dev/null 2>&1; then
  useradd --system --home-dir "${home}" --create-home --shell /bin/sh "${user}"
fi
usermod --password '*' --append --groups docker "${user}"
install -d -m 0750 -o "${user}" -g "${user}" "${home}"

install -d -m 0755 -o root -g root /usr/local/libexec
install -m 0755 -o root -g root scripts/deploy-host.sh "${cmd}"

# Root owns the key file, so the deploy user cannot add keys or options of its own.
install -d -m 0755 -o root -g root "${home}/.ssh"
printf 'restrict,command="%s" %s\n' "${cmd}" "${key}" > "${home}/.ssh/authorized_keys"
chown root:root "${home}/.ssh/authorized_keys"
chmod 0644 "${home}/.ssh/authorized_keys"

install -d -m 0750 -o root -g "${user}" "$(dirname "${env_file}")"
if [ ! -e "${env_file}" ]; then
  (
    umask 027
    cat > "${env_file}" <<EOF
# compose.yaml's settings for the production stack, read by ${cmd} on every deploy.
# Only root and ${user} can read this file; it never leaves the host. Changes apply at the
# next deploy (or run it by hand: sudo -u ${user} ${cmd} deploy X.Y.Z).

# Goes into the User-Agent sent to OpenStreetMap services, so they can reach you. Set it.
OBS_CONTACT=
# Shared by the app and the region agent (generated by deploy-host-setup.sh).
OBS_REGIONS_TOKEN=$(openssl rand -hex 32)
# The token the UI asks for to manage regions; empty makes them read-only (openssl rand -hex 32).
OBS_ADMIN_TOKEN=
# Loopback only: the reverse proxy on this host serves 80 and 443 (docs/deploy.md).
OBS_PORT=127.0.0.1:8080
# The reverse proxy as the app sees it: Docker's bridge gateway, which is in Docker's default
# address pools. Without it every client shares one rate limit.
OBS_TRUSTED_PROXIES=172.16.0.0/12
OBS_LOG_FORMAT=json
EOF
  )
  chown root:"${user}" "${env_file}"
  echo "wrote ${env_file}: set OBS_CONTACT (and OBS_ADMIN_TOKEN if you want to manage regions)"
fi

echo
echo "DEPLOY_KNOWN_HOSTS for the production environment (put DEPLOY_HOST's value in front):"
for pub in /etc/ssh/ssh_host_ed25519_key.pub /etc/ssh/ssh_host_ecdsa_key.pub; do
  if [ -r "${pub}" ]; then awk '{ print "<DEPLOY_HOST>", $1, $2 }' "${pub}"; fi
done
echo "Check: ssh ${user}@<DEPLOY_HOST> deploy X.Y.Z deploys a release; anything else is refused."
